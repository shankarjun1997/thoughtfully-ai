export const holidaysByDate: Record<string, Holiday[]> = holidays.reduce((map, holiday) => {
  (map[holiday.date] ??= []).push(holiday);
  return map;
}, {} as Record<string, Holiday[]>);

export function holidaysForMonth(year: number, monthIndex: number) {
  const prefix = `${year}-${String(monthIndex + 1).padStart(2, "0")}`;
  return holidays.filter((holiday) => holiday.date.startsWith(prefix));
}
